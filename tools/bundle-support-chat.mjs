// Builds deploy/support-chat.single-file.ts: the whole support-chat function in ONE file,
// for pasting into the Supabase dashboard editor (which cannot resolve ../_shared imports).
// Also writes deploy/all-migrations.sql (both migrations in order).
// Run: node tools/bundle-support-chat.mjs
import fs from 'node:fs';
import path from 'node:path';
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const F = p => path.join(ROOT, p);
const order = [
  'supabase/functions/_shared/pure.ts',
  'supabase/functions/_shared/providers.ts',
  'supabase/functions/_shared/escalation.ts',
  'supabase/functions/_shared/chatcore.ts',
  'supabase/functions/support-chat/index.ts',
];
const NPM = 'import { createClient } from "npm:@supabase/supabase-js@2";';
let out = `// Subora support chatbot: support-chat Edge Function (single-file build, phases 2 to 4).\n// GENERATED by tools/bundle-support-chat.mjs. Edit the modular files under supabase/functions, then rebuild.\n${NPM}\n`;
const tops = new Map();
for (const f of order) {
  let src = fs.readFileSync(F(f), 'utf8');
  src = src.split('\n')
    .filter(l => !/^import\b.*from\s+["']\.{1,2}\//.test(l) && l.trim() !== NPM)
    .join('\n').replace(/^export\s+/gm, '');
  for (const m of src.matchAll(/^(?:async\s+)?(?:const|let|var|function|class|interface|type)\s+([A-Za-z_$][\w$]*)/gm)) {
    if (tops.has(m[1])) throw new Error(`duplicate top-level name "${m[1]}" in ${f} and ${tops.get(m[1])}`);
    tops.set(m[1], f);
  }
  out += `\n// ===== ${f.replace('supabase/functions/', '')} =====\n${src.trim()}\n`;
}
if (/\nimport\b/.test(out.replace(NPM, ''))) throw new Error('leftover import in bundle');
fs.writeFileSync(F('deploy/support-chat.single-file.ts'), out);
const sql = ['supabase/migrations/20261026_support_chat.sql', 'supabase/migrations/20261027_chat_tickets.sql']
  .map(f => `-- ===== ${path.basename(f)} =====\n` + fs.readFileSync(F(f), 'utf8').trim()).join('\n\n');
fs.writeFileSync(F('deploy/all-migrations.sql'), sql + '\n');
console.log(`deploy/support-chat.single-file.ts  ${out.length} chars, ${tops.size} top-level names, no duplicates`);
console.log(`deploy/all-migrations.sql           ${sql.length} chars`);
